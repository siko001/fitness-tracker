import { expect, test } from '@playwright/test';

const food = { id: 'ai-test-panina', name: 'Tuna ftira', brand: 'Panina', group: 'Other', preparation: 'Ready to eat', custom: true, estimated: true, source: 'AI estimate · Groq', notes: 'Estimated bread and tuna filling; restaurant nutrition unavailable.', per100: { kcal: 230, protein: 12, carbs: 29, fat: 7, fibre: 3 } };
const proposal = (grams: number, existing = false) => ({ reply: `A ${grams} g portion, using the same estimated Panina ftira. Check the details before saving.`, items: [{ food, grams, existing, notes: food.notes }], draft: [{ ref: existing ? `food:${food.id}` : null, name: food.name, brand: food.brand, preparation: food.preparation, grams, per100: food.per100, portionLabel: '1 ftira', notes: food.notes, sourceUrls: [] }], warnings: [] });

test('conversation clarifies, changes a portion, requires review and reuses a saved restaurant food', async ({ page }) => {
  const requests: any[] = [];
  await page.route('**/api/food-assistant', route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: { configured: true } });
    const body = route.request().postDataJSON(); requests.push(body);
    if (requests.length === 1) return route.fulfill({ json: { reply: 'What size was the ftira? Would you like an estimate if Panina has no published nutrition?', items: [], draft: [], warnings: [] } });
    if (requests.length === 2) return route.fulfill({ json: proposal(300) });
    return route.fulfill({ json: proposal(150, requests.length > 3) });
  });
  await page.goto('/#diary');
  await page.getByRole('button', { name: 'Ask about food', exact: true }).click();
  const message = page.getByLabel('Message the food assistant'), send = page.getByRole('button', { name: 'Send', exact: true }), save = page.getByRole('button', { name: 'Save & log meal', exact: true });
  await message.fill('I am eating a tuna ftira from Panina.'); await send.click();
  await expect(page.getByRole('log')).toContainText('What size'); await expect(save).toBeDisabled();
  await message.fill('300 g, an estimate is fine.'); await send.click();
  await expect(page.getByLabel('Grams · Tuna ftira')).toHaveValue('300');
  await message.fill('Actually I only ate half of that.'); await send.click();
  await expect(page.getByLabel('Grams · Tuna ftira')).toHaveValue('150');
  expect(requests[2].messages).toHaveLength(5); expect(requests[2].draft[0].grams).toBe(300);
  await expect(page.locator('.assistant-food')).toContainText('Panina');
  await page.getByText('Nutrition & source', { exact: true }).click();
  await expect(page.locator('.assistant-food')).toContainText('restaurant nutrition unavailable');
  await expect(save).toBeDisabled();
  await page.getByLabel('Meal', { exact: true }).selectOption('Lunch');
  await page.getByLabel('Time eaten').fill('13:10');
  await page.getByLabel('I’ve checked the matches, portions and any estimates.').check();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: 'test-results/assistant-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/assistant-mobile.png' });
  const header = (await page.locator('.modal-header').boundingBox())!, footer = (await page.locator('.modal-footer').boundingBox())!;
  await page.locator('.modal-body').evaluate(el => el.scrollTop = el.scrollHeight);
  expect((await page.locator('.modal-header').boundingBox())!.y).toBe(header.y);
  expect((await page.locator('.modal-footer').boundingBox())!.y).toBe(footer.y);
  await expect(save).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 844, height: 390 });
  expect(await page.locator('.modal-body').evaluate(el => el.clientHeight)).toBeGreaterThan(70);
  await expect(save).toBeInViewport();
  await page.setViewportSize({ width: 390, height: 844 });
  await save.click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.locator('.diary-entry')).toContainText('Tuna ftira · Panina');
  await expect(page.locator('.diary-entry')).toContainText('13:10');
  await page.getByRole('button', { name: 'Ask about food', exact: true }).click();
  await message.fill('Another half of my saved Panina ftira.'); await send.click();
  await expect(page.locator('.assistant-food')).toContainText('Already saved');
  expect(requests[3].foods.filter((f: any) => f.id === food.id)).toHaveLength(1);
  await page.getByLabel('I’ve checked the matches, portions and any estimates.').check(); await save.click();
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.getByRole('button', { name: 'Food library', exact: true }).click();
  await page.getByLabel('Search food library').fill('Panina');
  await expect(page.locator('.food-row')).toHaveCount(1);
});

test('list lookup works offline and failed AI replies retain the unsaved correction without storing the key', async ({ page, context }) => {
  await page.route('**/api/food-assistant', route => route.fulfill({ status: route.request().method() === 'GET' ? 200 : 429, json: route.request().method() === 'GET' ? { configured: false } : { error: 'Usage limit reached. Try later.' } }));
  await page.goto('/#foods');
  await page.getByRole('button', { name: 'Find foods with AI', exact: true }).click();
  await page.getByLabel('Groq API key', { exact: true }).fill('gsk_example_not_a_real_key_123456');
  const message = page.getByLabel('Message the food assistant');
  await message.fill('Chicken breast 200 g\nOlive oil 10 g');
  await page.getByRole('button', { name: 'Find list', exact: true }).click();
  await expect(page.locator('.assistant-food')).toHaveCount(2);
  await message.fill('Half the chicken, please.'); await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Usage limit reached');
  await expect(message).toHaveValue('Half the chicken, please.');
  await expect(page.locator('.assistant-food')).toHaveCount(2);
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload(); await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true); await page.reload();
  await page.getByRole('button', { name: 'Find foods with AI', exact: true }).click();
  await expect(page.getByLabel('Groq API key', { exact: true })).toHaveValue('');
  await message.fill('Chicken breast 200 g\nOlive oil 10 g');
  await page.getByRole('button', { name: 'Find list', exact: true }).click();
  await expect(page.locator('.assistant-food')).toHaveCount(2);
  await expect(page.getByRole('button', { name: 'Save to library', exact: true })).toBeDisabled();
  await page.getByLabel('I’ve checked the matches, portions and any estimates.').check();
  await page.getByRole('button', { name: 'Save to library', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
});
